import os
from typing import Dict, Any, Optional

from moviepy import (
    VideoFileClip,
    AudioFileClip,
    CompositeVideoClip,
    CompositeAudioClip,
    concatenate_videoclips,
    TextClip,
)
from moviepy.audio.fx import MultiplyVolume
from moviepy.video.fx import CrossFadeIn, Resize, MultiplySpeed


class VideoEditor:
    """
    Phase 5: Assembles the final video from an Edit Decision List (EDL)
    generated by the CreativeDirector. Each timeline item is placed at the
    exact start/end position specified by the director, with full support
    for transitions, pacing styles, and audio ducking.
    """

    ORIGINAL_AUDIO_VOLUME = 0.3   # Duck original clip audio when music plays
    MUSIC_VOLUME = 0.9
    DEFAULT_FADE_DURATION = 0.3

    # Speed multipliers for pacing styles defined by the director
    PACING_SPEED = {
        "speed-ramp": 1.5,       # faster cut
        "jump-cut": 1.0,         # no speed change, handled by clip selection
        "cinematic-slow": 0.75,  # slower, more dramatic
    }

    def __init__(self, clips_dir: str, output_dir: str = "data/exports"):
        self.clips_dir = clips_dir
        self.output_dir = output_dir
        os.makedirs(output_dir, exist_ok=True)

    def _find_font(self) -> str:
        """Finds a suitable TTF font on the system for text overlays."""
        candidates = [
            "C:/Windows/Fonts/arialbd.ttf",   # Windows Arial Bold
            "C:/Windows/Fonts/arial.ttf",
            "C:/Windows/Fonts/calibri.ttf",
            "C:/Windows/Fonts/verdana.ttf",
            "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",  # Linux
        ]
        for path in candidates:
            if os.path.exists(path):
                return path
        raise FileNotFoundError("No suitable font found. Please ensure Arial or Calibri is installed.")

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def render(
        self,
        edl: Dict[str, Any],
        music_path: Optional[str] = None,
        output_filename: str = "shortify_output.mp4"
    ) -> str:
        """
        Renders the final video from an EDL produced by CreativeDirector.

        The director's EDL specifies:
          - clip_name, start_in_clip, end_in_clip  (what to take from source)
          - timeline_start, timeline_end            (where it lands on the timeline)
          - transition                              (how to join to the previous clip)
          - details.pacing_style                   (speed-ramp / jump-cut / cinematic-slow)
        """
        timeline = edl.get("timeline", [])
        if not timeline:
            raise ValueError("EDL timeline is empty. Nothing to render.")

        # Ensure timeline is chronologically ordered
        timeline.sort(key=lambda x: float(x.get("timeline_start", 0.0)))

        title = edl.get("title", "Untitled")
        print(f"Rendering '{title}' - {len(timeline)} director-specified segments...")

        processed_clips = []

        for i, item in enumerate(timeline):
            clip_name   = item.get("clip_name", "")
            start_in    = float(item.get("start_in_clip", 0.0))
            end_in      = float(item.get("end_in_clip", 0.0))
            tl_start    = float(item.get("timeline_start", 0.0))
            tl_end      = float(item.get("timeline_end", end_in - start_in))
            transition  = item.get("transition", "none").lower()
            details     = item.get("details", {})
            pacing      = details.get("pacing_style", "jump-cut").lower()

            clip_path = os.path.join(self.clips_dir, clip_name)
            if not os.path.exists(clip_path):
                print(f"  Warning: clip not found, skipping -> {clip_name}")
                continue

            # 1. Load & trim from source
            raw = VideoFileClip(clip_path)
            safe_end = min(end_in, raw.duration)
            clip = raw.subclipped(start_in, safe_end)

            # 2. Resize and Center-Crop to 9:16 (1080x1920)
            target_w, target_h = (1080, 1920)
            clip_w, clip_h = clip.size
            
            # Calculate scaling to fill target
            scale = max(target_w / clip_w, target_h / clip_h)
            new_w, new_h = int(clip_w * scale), int(clip_h * scale)
            
            # Resize
            clip = clip.with_effects([Resize(width=new_w, height=new_h)])
            
            # Center crop
            x1 = (new_w - target_w) // 2
            y1 = (new_h - target_h) // 2
            clip = clip.cropped(x1=x1, y1=y1, width=target_w, height=target_h)
            
            # 2b. Apply pacing style (speed multiplier)
            speed = self.PACING_SPEED.get(pacing, 1.0)
            if speed != 1.0:
                clip = clip.with_effects([MultiplySpeed(speed)])

            # 3. Match timeline duration exactly
            target_duration = round(tl_end - tl_start, 4)
            if target_duration > 0:
                # If clip is too short, we adjust speed (slow down) to fit, up to 0.5x
                # If it's still too short, we let it be and it will just end early in its slot.
                if clip.duration < target_duration:
                    speed_factor = clip.duration / target_duration
                    if speed_factor >= 0.5:
                        clip = clip.with_effects([MultiplySpeed(speed_factor)])
                    clip = clip.with_duration(target_duration)
                else:
                    clip = clip.with_duration(target_duration)

            # Set the explicit start time on the timeline
            clip = clip.with_start(tl_start)

            # 4. Apply transitions
            if transition in ("fade", "crossfade") and i > 0:
                fade_dur = min(self.DEFAULT_FADE_DURATION, clip.duration / 2)
                clip = clip.with_effects([CrossFadeIn(fade_dur)])

            elif transition == "zoom_in":
                clip = clip.with_effects([Resize(lambda t: 1 + 0.04 * t)])
            
            elif transition == "zoom_out":
                clip = clip.with_effects([Resize(lambda t: 1.1 - 0.04 * t)])

            elif transition in ("slide_left", "slide_right"):
                # Simple slide simulation using Clip.with_position
                # For a more professional slide, we'd need CompositeVideoClip transitions
                # but for now we'll use a horizontal offset if possible
                pass

            # 5. Duck original audio
            if clip.audio is not None:
                # Only duck if there is actually audio in the clip
                clip = clip.with_audio(
                    clip.audio.with_effects([MultiplyVolume(self.ORIGINAL_AUDIO_VOLUME)])
                )

            # 6. Apply text overlay
            text_overlay = item.get("text_overlay", "").strip()
            if text_overlay:
                font_path = self._find_font()
                w, h = clip.size
                txt_clip = TextClip(
                    text=text_overlay,
                    font=font_path,
                    font_size=70,
                    color="white",
                    stroke_color="black",
                    stroke_width=2,
                    method="caption",
                    size=(int(w * 0.8), None), # Wrap text if it gets too long
                )
                txt_clip = (
                    txt_clip
                    .with_duration(clip.duration)
                    .with_position(("center", "center")) # Put text in the middle
                )
                clip = CompositeVideoClip([clip, txt_clip])

            processed_clips.append(clip)
            print(
                f"  [{i+1}/{len(timeline)}] {clip_name} | "
                f"src {start_in:.2f}s-{safe_end:.2f}s | "
                f"timeline {tl_start:.2f}s-{tl_end:.2f}s | "
                f"pacing: {pacing} | transition: {transition}"
            )

        if not processed_clips:
            raise RuntimeError("No valid clips were processed. Check clips directory and EDL.")

        # 6. Assemble in a CompositeVideoClip for absolute timeline positioning
        print("Assembling clips in CompositeVideoClip...")
        from moviepy import ColorClip
        
        # Use total duration from EDL or calculate from max timeline_end
        final_duration = edl.get("total_duration", 0.0)
        if final_duration <= 0:
            final_duration = max([float(item.get("timeline_end", 0.0)) for item in timeline])
        
        # Create a black background as the base layer
        base_layer = ColorClip(
            size=(1080, 1920),
            color=(0, 0, 0),
            duration=final_duration
        )
        
        final_video = CompositeVideoClip([base_layer] + processed_clips)

        # 7. Mix background music
        if music_path and os.path.exists(music_path):
            print(f"Mixing background music: {music_path}")
            music = AudioFileClip(music_path)
            
            music_start = float(edl.get("music_start_offset", 0.0))
            music_end = music_start + final_video.duration
            
            # Ensure we don't exceed music duration
            if music_end > music.duration:
                music_start = max(0, music.duration - final_video.duration)
                music_end = music.duration
            
            music = music.subclipped(music_start, music_end)

            # Professional music finishing
            from moviepy.audio.fx import AudioFadeOut
            music = music.with_effects([
                MultiplyVolume(self.MUSIC_VOLUME),
                AudioFadeOut(1.5) # Smooth fade at the very end
            ])

            if final_video.audio:
                mixed = CompositeAudioClip([final_video.audio, music])
            else:
                mixed = music
            final_video = final_video.with_audio(mixed)

        # 8. Write output
        output_path = os.path.join(self.output_dir, output_filename)
        print(f"Writing final video -> {output_path}")
        final_video.write_videofile(
            output_path,
            codec="libx264",
            audio_codec="aac",
            temp_audiofile=os.path.join(self.output_dir, "temp_audio.m4a"),
            remove_temp=True,
            logger="bar",
        )

        for clip in processed_clips:
            clip.close()
        final_video.close()

        print(f"Render complete! Output: {output_path}")
        return output_path


if __name__ == "__main__":
    print("VideoEditor module loaded successfully.")
